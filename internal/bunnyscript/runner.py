#!/usr/bin/env python3
"""BunnyMind generated HTTP evidence runner.

Generated by a fixed, reviewed Python template. Its embedded PLAN is
operator-approved, not code supplied by an untrusted web page. No redirects
are followed, no commands are executed, and the only network destination is
a numeric-loopback fixture or the trusted localhost HTTPS CONNECT proxy.
The resulting raw transcript must be encrypted immediately by the Go parent.
"""
import base64
import hashlib
import http.client
import json
import os
import ssl
import sys
import time
import urllib.parse

PLAN = json.loads(__BUNNY_PLAN_LITERAL__)
MAX_BODY = 65536

def digest(data):
    return hashlib.sha256(data).hexdigest()

def request_one(test, proxy):
    origin = PLAN["origin"]
    base = urllib.parse.urlsplit(origin)
    host = base.hostname
    method = test["method"]
    path = test["path"]
    if method not in ("GET", "HEAD"):
        raise ValueError("unapproved method")
    parsed = urllib.parse.urlsplit(path)
    if not path.startswith("/") or path.startswith("//") or parsed.scheme or parsed.netloc or parsed.fragment:
        raise ValueError("unsafe request target")
    headers = {
        "Host": base.netloc,
        "User-Agent": "BunnyMind-Python-Evidence/0.29 (operator-approved)",
        "Accept-Encoding": "identity",
        "Connection": "close",
    }
    actor = test.get("persona", "")
    if actor:
        cookie = os.environ.get("BUNNY_PROOF_COOKIE_" + actor.upper(), "")
        if cookie:
            if any(x in cookie for x in "\r\n") or len(cookie) > 4096:
                raise ValueError("invalid test identity cookie")
            headers["Cookie"] = cookie
    if base.scheme == "http":
        if host not in ("127.0.0.1", "::1") or proxy:
            raise ValueError("plain HTTP available only to local fixtures")
        conn = http.client.HTTPConnection(host,base.port,timeout=8)
    elif base.scheme == "https":
        if not proxy:
            raise ValueError("HTTPS requires the approved pinned egress proxy")
        pu = urllib.parse.urlsplit(proxy)
        if pu.scheme != "http" or pu.hostname != "127.0.0.1" or not pu.port:
            raise ValueError("untrusted proxy address")
        conn = http.client.HTTPConnection(pu.hostname,pu.port,timeout=8)
        conn.set_tunnel(host,443)
        conn.connect()
        conn.sock = ssl.create_default_context().wrap_socket(conn.sock,server_hostname=host)
    else:
        raise ValueError("unsupported URL scheme")
    request_bytes = (method + " " + path + " HTTP/1.1\r\n" +
                     "".join(k + ": " + v + "\r\n" for k,v in headers.items()) + "\r\n").encode("utf-8")
    started = time.time()
    try:
        conn.request(method,path,headers=headers)
        resp = conn.getresponse()
        payload = resp.read(MAX_BODY+1)
        truncated = len(payload) > MAX_BODY
        if truncated:
            payload = payload[:MAX_BODY]
        status = resp.status
        response_headers = resp.getheaders()
        status_line = "HTTP/1.1 " + str(status) + " " + resp.reason + "\r\n"
        header_bytes = (status_line + "".join(k + ": " + v + "\r\n" for k,v in response_headers) +
                        "\r\n").encode("utf-8",errors="replace")
        response_bytes = header_bytes + payload
        present = PLAN["marker"].encode("utf-8") in payload
        return {
            "sample_id":test["sample_id"],
            "kind":test["kind"],
            "persona":actor,
            "status":status,
            "content_sha256":digest(payload),
            "request_sha256":digest(request_bytes),
            "response_sha256":digest(response_bytes),
            "marker_present":present,
            "truncated":truncated,
            "duration_ms":round((time.time()-started)*1000,3),
            "observed_at":time.strftime("%Y-%m-%dT%H:%M:%SZ",time.gmtime()),
            "request_b64":base64.b64encode(request_bytes).decode("ascii"),
            "response_b64":base64.b64encode(response_bytes).decode("ascii"),
        }
    finally:
        conn.close()

def main():
    if len(sys.argv)!=4 or sys.argv[1]!="--out":
        raise SystemExit("usage: scenario.py --out <private-file> <approved-proxy-or-none>")
    out_path, proxy = sys.argv[2], sys.argv[3]
    if proxy=="none":
        proxy=""
    observations=[]
    for i,test in enumerate(PLAN["cases"]):
        if i and PLAN["min_interval_ms"]:
            time.sleep(PLAN["min_interval_ms"]/1000.0)
        observations.append(request_one(test,proxy))
    # The only raw transcript representation is this private, short-lived
    # evidence handoff file. The Go parent encrypts and securely removes it.
    data=json.dumps({"version":1,"engagement_id":PLAN["engagement_id"],
                     "run_id":PLAN["run_id"],"observations":observations},
                     sort_keys=True,separators=(",",":")).encode("utf-8")
    fd=os.open(out_path,os.O_WRONLY|os.O_CREAT|os.O_EXCL,0o600)
    with os.fdopen(fd,"wb") as stream:
        stream.write(data)
        stream.flush()
        os.fsync(stream.fileno())
    print(json.dumps({"samples":len(observations),"status":"captured_for_encryption"}))

if __name__=="__main__":
    try:
        main()
    except Exception as exc:
        # Do not print URLs, exception payloads, headers, or response bodies.
        print(json.dumps({"status":"failed","reason":type(exc).__name__}),file=sys.stderr)
        raise SystemExit(2)
